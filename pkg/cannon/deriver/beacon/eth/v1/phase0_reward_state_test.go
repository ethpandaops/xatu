// The fixtures are minimal-preset phase0 cases from ethereum/consensus-spec-tests v1.5.0, generated by the Python
// reference spec: rewards/* hold a state and the get_*_deltas the spec computed for it, random/* and finality/* a
// pre-state, the blocks applied to it and the resulting post-state.
const phase0RewardFixtures = "testdata/phase0_rewards"

// TestPhase0EpochRewardsMatchSpecDeltas checks each reward component against the deltas the reference spec computed.
func TestPhase0EpochRewardsMatchSpecDeltas(t *testing.T) {
	dirs, err := filepath.Glob(filepath.Join(phase0RewardFixtures, "rewards", "*", "pyspec_tests", "*"))
	require.NoError(t, err)
	require.NotEmpty(t, dirs)

	for _, dir := range dirs {
		t.Run(filepath.Base(dir), func(t *testing.T) {
			state := loadFixtureState(t, filepath.Join(dir, "pre.ssz_snappy"))

			rewards, err := computePhase0EpochRewards(context.Background(), configs.Minimal, state)
			require.NoError(t, err)

			count := validatorCount(t, state)
			got := map[string][]int64{
				"source":             make([]int64, count),
				"target":             make([]int64, count),
				"head":               make([]int64, count),
				"inclusion_delay":    make([]int64, count),
				"inactivity_penalty": make([]int64, count),
			}

			for _, a := range rewards.Attesters {
				got["source"][a.ValidatorIndex] = a.Source
				got["target"][a.ValidatorIndex] = a.Target
				got["head"][a.ValidatorIndex] = a.Head
				got["inclusion_delay"][a.ValidatorIndex] += int64(a.InclusionDelay)
				got["inactivity_penalty"][a.ValidatorIndex] = a.Inactivity
			}

			// The spec's inclusion delay deltas pay the proposer's share to the proposer's own index.
			for inclusion, gwei := range rewards.ProposerCredits {
				got["inclusion_delay"][inclusion.ProposerIndex] += int64(gwei)
			}

			for component, values := range got {
				want := loadFixtureDeltas(t, filepath.Join(dir, component+"_deltas.ssz_snappy"))
				require.Equal(t, want, values, component)
			}
		})
	}
}

// TestPhase0RewardsReconcileBalances replays reference-spec chains and checks that every validator's balance change
// from the pre-state to the post-state equals the computed attestation deltas and proposer rewards, plus the deposits
// and slashing penalties in between, to the gwei.
func TestPhase0RewardsReconcileBalances(t *testing.T) {
	var dirs []string

	for _, pattern := range []string{"random/random/pyspec_tests/*", "finality/finality/pyspec_tests/*"} {
		matches, err := filepath.Glob(filepath.Join(phase0RewardFixtures, pattern))
		require.NoError(t, err)

		dirs = append(dirs, matches...)
	}

	require.NotEmpty(t, dirs)

	for _, dir := range dirs {
		t.Run(filepath.Base(dir), func(t *testing.T) {
			reconcileFixtureChain(t, dir)
		})
	}
}

func reconcileFixtureChain(t *testing.T, dir string) {
	t.Helper()

	ctx := context.Background()
	spec := configs.Minimal
	slotsPerEpoch := uint64(spec.SLOTS_PER_EPOCH)

	pre := loadFixtureState(t, filepath.Join(dir, "pre.ssz_snappy"))
	post := loadFixtureState(t, filepath.Join(dir, "post.ssz_snappy"))

	preFlats := fixtureFlats(t, pre)

	expected := make([]int64, 0, len(preFlats))
	for _, balance := range fixtureBalances(t, pre) {
		expected = append(expected, int64(balance))
	}

	stateCopy, err := pre.CopyState()
	require.NoError(t, err)

	state := &beacon.StandardUpgradeableBeaconState{BeaconState: stateCopy}

	epc, err := zcommon.NewEpochsContext(spec, state.BeaconState)
	require.NoError(t, err)

	endOfEpoch := map[phase0.Epoch]*phase0EpochRewards{}
	transitions := 0

	// advance processes empty slots up to target; at each epoch's last slot the transition about to run is
	// reconciled with the computed rewards, and its process_slashings penalties are applied from the spec formula.
	advance := func(target zcommon.Slot, reconcile bool) {
		for {
			slot, slotErr := state.Slot()
			require.NoError(t, slotErr)

			if slot >= target {
				return
			}

			if uint64(slot+1)%slotsPerEpoch == 0 {
				view, ok := state.BeaconState.(*zphase0.BeaconStateView)
				require.True(t, ok)

				rewards, rewardsErr := computePhase0EpochRewards(ctx, spec, view)
				require.NoError(t, rewardsErr)

				if _, ok := endOfEpoch[rewards.StateEpoch]; !ok {
					endOfEpoch[rewards.StateEpoch] = rewards
				}

				if reconcile {
					transitions++

					for _, a := range rewards.Attesters {
						expected[a.ValidatorIndex] += a.Head + a.Target + a.Source + int64(a.InclusionDelay) + a.Inactivity
					}

					for inclusion, gwei := range rewards.ProposerCredits {
						expected[inclusion.ProposerIndex] += int64(gwei)
					}

					for index, penalty := range specSlashingsPenalties(t, spec, view) {
						expected[index] -= int64(penalty)
					}
				}
			}

			require.NoError(t, zcommon.ProcessSlots(ctx, spec, epc, state, slot+1))
		}
	}

	blocksByEpoch := map[phase0.Epoch][]*phase0.BeaconBlock{}

	blockFiles, err := filepath.Glob(filepath.Join(dir, "blocks_*.ssz_snappy"))
	require.NoError(t, err)

	genesisValidatorsRoot, err := pre.GenesisValidatorsRoot()
	require.NoError(t, err)

	digest := zcommon.ComputeForkDigest(spec.GENESIS_FORK_VERSION, genesisValidatorsRoot)

	for i := range blockFiles {
		raw := readFixture(t, filepath.Join(dir, "blocks_"+strconv.Itoa(i)+".ssz_snappy"))

		zblock := new(zphase0.SignedBeaconBlock)
		require.NoError(t, zblock.Deserialize(spec, codec.NewDecodingReader(bytes.NewReader(raw), uint64(len(raw)))))

		block := new(phase0.SignedBeaconBlock)
		require.NoError(t, block.UnmarshalSSZ(raw))

		advance(zblock.Message.Slot, true)

		before := fixtureFlats(t, state.BeaconState)
		pubkeys := fixturePubkeyIndices(t, state.BeaconState)

		require.NoError(t, zcommon.PostSlotTransition(ctx, spec, epc, state, zblock.Envelope(spec, digest), true))

		after := fixtureFlats(t, state.BeaconState)
		afterPubkeys := fixturePubkeyIndices(t, state.BeaconState)

		// Deposits top up an existing validator or append a new one; an invalid new-validator deposit is skipped.
		for _, deposit := range block.Message.Body.Deposits {
			pubkey := [48]byte(deposit.Data.PublicKey)

			if index, ok := pubkeys[pubkey]; ok {
				expected[index] += int64(deposit.Data.Amount)

				continue
			}

			if index, ok := afterPubkeys[pubkey]; ok {
				require.Equal(t, len(expected), index)

				pubkeys[pubkey] = index

				expected = append(expected, int64(deposit.Data.Amount))
			}
		}

		// slash_validator's initial penalty; the whistleblower reward is the computed block reward checked below.
		for index := range before {
			if !before[index].Slashed && after[index].Slashed {
				expected[index] -= int64(before[index].EffectiveBalance / zcommon.Gwei(spec.MIN_SLASHING_PENALTY_QUOTIENT))
			}
		}

		epoch := phase0.Epoch(uint64(block.Message.Slot) / slotsPerEpoch)
		blocksByEpoch[epoch] = append(blocksByEpoch[epoch], block.Message)
	}

	postSlot, err := post.Slot()
	require.NoError(t, err)

	if slot, _ := state.Slot(); slot < postSlot {
		advance(postSlot, true)
	}

	require.Equal(t, post.HashTreeRoot(tree.GetHashFn()), state.HashTreeRoot(tree.GetHashFn()), "replay must reproduce the reference post-state")

	// Run empty slots past the post-state so every block epoch has its end-of-epoch and next-epoch rewards.
	lastEpoch := phase0.Epoch(0)
	for epoch := range blocksByEpoch {
		lastEpoch = max(lastEpoch, epoch)
	}

	advance(zcommon.Slot((uint64(lastEpoch)+2)*slotsPerEpoch), false)

	fixtureBlocks := map[phase0Inclusion]bool{}

	for _, blocks := range blocksByEpoch {
		for _, block := range blocks {
			fixtureBlocks[phase0Inclusion{Slot: block.Slot, ProposerIndex: block.ProposerIndex}] = true
		}
	}

	for epoch, blocks := range blocksByEpoch {
		previous, ok := endOfEpoch[epoch-1]
		if !ok {
			// Slashings before the pre-state count as before the epoch: their blocks are not in the fixture.
			previous = &phase0EpochRewards{StateEpoch: epoch - 1, Slashed: map[phase0.ValidatorIndex]uint64{}}

			for index := range preFlats {
				if preFlats[index].Slashed {
					previous.Slashed[phase0.ValidatorIndex(index)] = 0
				}
			}
		}

		rows, err := computePhase0BlockRewards(blocks, slotsPerEpoch, previous,
			onlyFixtureBlocks(endOfEpoch[epoch], fixtureBlocks),
			onlyFixtureBlocks(endOfEpoch[epoch+1], fixtureBlocks))
		require.NoError(t, err)

		for _, row := range rows {
			expected[row.ProposerIndex] += int64(row.ProposerSlashings + row.AttesterSlashings)
		}
	}

	got := make([]int64, 0, len(expected))
	for _, balance := range fixtureBalances(t, post) {
		got = append(got, int64(balance))
	}

	require.Positive(t, transitions, "the chain must cross at least one epoch transition")
	require.Equal(t, got, expected)
}

// onlyFixtureBlocks drops the proposer rewards of blocks that are not in the fixture: those before its pre-state, and
// the random inclusions the reference spec's test generator wrote into synthetic pre-states.
func onlyFixtureBlocks(rewards *phase0EpochRewards, blocks map[phase0Inclusion]bool) *phase0EpochRewards {
	filtered := &phase0EpochRewards{
		StateEpoch:      rewards.StateEpoch,
		Attesters:       rewards.Attesters,
		ProposerCredits: map[phase0Inclusion]uint64{},
		Slashed:         rewards.Slashed,
	}

	for inclusion, gwei := range rewards.ProposerCredits {
		if blocks[inclusion] {
			filtered.ProposerCredits[inclusion] = gwei
		}
	}

	return filtered
}

// specSlashingsPenalties is phase0 process_slashings, written from the spec independently of the code under test.
func specSlashingsPenalties(t *testing.T, spec *zcommon.Spec, state *zphase0.BeaconStateView) map[int]uint64 {
	t.Helper()

	slot, err := state.Slot()
	require.NoError(t, err)

	epoch := spec.SlotToEpoch(slot)
	flats := fixtureFlats(t, state)

	total := uint64(0)

	for i := range flats {
		if flats[i].IsActive(epoch) {
			total += uint64(flats[i].EffectiveBalance)
		}
	}

	total = max(total, uint64(spec.EFFECTIVE_BALANCE_INCREMENT))

	slashings, err := state.Slashings()
	require.NoError(t, err)

	sum, err := slashings.Total()
	require.NoError(t, err)

	adjusted := min(uint64(sum)*uint64(spec.PROPORTIONAL_SLASHING_MULTIPLIER), total)
	increment := uint64(spec.EFFECTIVE_BALANCE_INCREMENT)

	out := map[int]uint64{}

	for i := range flats {
		if flats[i].Slashed && epoch+spec.EPOCHS_PER_SLASHINGS_VECTOR/2 == flats[i].WithdrawableEpoch {
			out[i] = uint64(flats[i].EffectiveBalance) / increment * adjusted / total * increment
		}
	}

	return out
}

func readFixture(t *testing.T, path string) []byte {
	t.Helper()

	compressed, err := os.ReadFile(path)
	require.NoError(t, err)

	raw, err := snappy.Decode(nil, compressed)
	require.NoError(t, err)

	return raw
}

func loadFixtureState(t *testing.T, path string) *zphase0.BeaconStateView {
	t.Helper()

	raw := readFixture(t, path)

	state, err := zphase0.AsBeaconStateView(zphase0.BeaconStateType(configs.Minimal).Deserialize(
		codec.NewDecodingReader(bytes.NewReader(raw), uint64(len(raw)))))
	require.NoError(t, err)

	return state
}

// loadFixtureDeltas decodes an SSZ Deltas container (two uint64 lists) into net rewards minus penalties.
func loadFixtureDeltas(t *testing.T, path string) []int64 {
	t.Helper()

	raw := readFixture(t, path)
	rewardsOffset := binary.LittleEndian.Uint32(raw[0:4])
	penaltiesOffset := binary.LittleEndian.Uint32(raw[4:8])

	rewards := raw[rewardsOffset:penaltiesOffset]
	penalties := raw[penaltiesOffset:]
	require.Len(t, penalties, len(rewards))

	out := make([]int64, len(rewards)/8)
	for i := range out {
		out[i] = int64(binary.LittleEndian.Uint64(rewards[i*8:])) - int64(binary.LittleEndian.Uint64(penalties[i*8:]))
	}

	return out
}

func validatorCount(t *testing.T, state zcommon.BeaconState) int {
	t.Helper()

	return len(fixtureFlats(t, state))
}

func fixtureFlats(t *testing.T, state zcommon.BeaconState) []zcommon.FlatValidator {
	t.Helper()

	vals, err := state.Validators()
	require.NoError(t, err)

	flats, err := zcommon.FlattenValidators(vals)
	require.NoError(t, err)

	return flats
}

func fixtureBalances(t *testing.T, state zcommon.BeaconState) []zcommon.Gwei {
	t.Helper()

	balances, err := state.Balances()
	require.NoError(t, err)

	all, err := balances.AllBalances()
	require.NoError(t, err)

	return all
}

func fixturePubkeyIndices(t *testing.T, state zcommon.BeaconState) map[[48]byte]int {
	t.Helper()

	vals, err := state.Validators()
	require.NoError(t, err)

	count, err := vals.ValidatorCount()
	require.NoError(t, err)

	out := make(map[[48]byte]int, count)

	for i := uint64(0); i < count; i++ {
		val, err := vals.Validator(zcommon.ValidatorIndex(i))
		require.NoError(t, err)

		pubkey, err := val.Pubkey()
		require.NoError(t, err)

		out[pubkey] = int(i)
	}

	return out
}
